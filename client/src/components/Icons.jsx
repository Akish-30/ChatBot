export function MessageStatusTicks({ status }) {
  if (status === 'sent') {
    // Single gray check
    return (
      <span className="tick-icon tick-sent" title="Sent">
        <svg viewBox="0 0 16 15" width="16" height="15" fill="none">
          <path
            d="M15.01 3.316l-.478-.372a.365.365 0 0 0-.51.063L6.566 11.84a.32.32 0 0 1-.484.033L1.891 7.769a.366.366 0 0 0-.515.006l-.423.433a.364.364 0 0 0 .006.514l5.258 5.185c.143.14.361.125.484-.033l8.372-10.048a.365.365 0 0 0-.063-.51z"
            fill="currentColor"
          />
        </svg>
      </span>
    );
  }

  // Double check (gray for delivered, vibrant blue #53bdeb for read)
  const isRead = status === 'read';
  return (
    <span
      className={`tick-icon ${isRead ? 'tick-read' : 'tick-delivered'}`}
      title={isRead ? 'Read' : 'Delivered'}
    >
      <svg viewBox="0 0 16 15" width="16" height="15" fill="none">
        <path
          d="M15.01 3.316l-.478-.372a.365.365 0 0 0-.51.063L8.666 9.88a.32.32 0 0 1-.484.032l-.358-.325a.32.32 0 0 0-.484.032l-.378.48a.418.418 0 0 0 .036.54l1.32 1.267a.32.32 0 0 0 .484-.034l6.272-8.048a.366.366 0 0 0-.064-.512zm-4.1 0l-.478-.372a.365.365 0 0 0-.51.063L4.566 9.88a.32.32 0 0 1-.484.032L1.892 7.77a.366.366 0 0 0-.516.005l-.423.433a.364.364 0 0 0 .006.514l3.255 3.185a.32.32 0 0 0 .484-.033l6.272-8.048a.365.365 0 0 0-.063-.51z"
          fill="currentColor"
        />
      </svg>
    </span>
  );
}

